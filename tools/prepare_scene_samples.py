def save_image(path, image):
    extension = path.suffix
    args = [cv2.IMWRITE_JPEG_QUALITY, 96] if extension == ".jpg" else []
    ok, data = cv2.imencode(extension, image, args)
    if not ok:
        raise RuntimeError(f"Cannot encode {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    data.tofile(str(path))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("data/samples"))
    args = parser.parse_args()
    out = args.output
    out.mkdir(parents=True, exist_ok=True)
    sources = []
    overview = []
    counts = {}
    for camera, objects in SCENES.items():
        camera_id = f"camera_{camera}"
        source = Path(f"data/video/{camera_id}.mkv")
        start = 0 if camera == 5 else 30
        frame = next(iter_video(source, start_sec=start, end_sec=start + 1))
        image = frame.image
        height, width = image.shape[:2]
        scale = np.array([width / 1296, height / 972])
        save_image(out / f"{camera_id}.jpg", image)
        shapes = []
        overlay = image.copy()
        outlines = image.copy()
        union = np.zeros((height, width), np.uint8)
        instances = np.zeros((height, width), np.uint16)
        shape_count = 0
        for object_id, obj in enumerate(objects, 1):
            mask = np.zeros((height, width), np.uint8)
            for part in obj["parts"]:
                points = np.rint(np.asarray(part) * scale).astype(np.int32)
                if len(points) < 3 or cv2.contourArea(points) <= 0:
                    raise ValueError(f"Invalid polygon {camera_id} {obj['name']}")
                if not (
                    (points >= 0).all() and (points[:, 0] < width).all() and (points[:, 1] < height).all()
                ):
                    raise ValueError("Polygon out of bounds")
                cv2.fillPoly(mask, [points], 255)
                shapes.append(
                    {
                        "label": obj["label"],
                        "points": points.tolist(),
                        "group_id": object_id,
                        "description": obj["name"],
                        "shape_type": "polygon",
                        "flags": {},
                        "mask": None,
                    }
                )
                shape_count += 1
            if not mask.any():
                raise ValueError("Empty object mask")
            color = [(80, 255, 0), (255, 140, 0), (0, 180, 255), (255, 40, 220), (0, 255, 220)][
                (object_id - 1) % 5
            ]
            if obj["label"] != "furniture":
                color = (0, 80, 255)
            overlay[mask > 0] = color
            union[mask > 0] = 255
            instances[mask > 0] = object_id
            contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
            cv2.drawContours(outlines, contours, -1, color, 3)
            main_contour = max(contours, key=cv2.contourArea)
            x, y, w, h = cv2.boundingRect(main_contour)
            anchor = (x, min(height - 10, max(32, y + 24)))
            cv2.putText(outlines, str(object_id), anchor, cv2.FONT_HERSHEY_SIMPLEX, 0.9, (0, 0, 0), 5)
            cv2.putText(outlines, str(object_id), anchor, cv2.FONT_HERSHEY_SIMPLEX, 0.9, color, 2)
            save_image(out / "masks" / camera_id / f"{object_id:03d}.png", mask)
        # Preserve clear source pixels; tint only inside polygons and retain sharp outlines.
        annotated = cv2.addWeighted(overlay, 0.18, outlines, 0.82, 0)
        save_image(out / f"{camera_id}.annotated.jpg", annotated)
        save_image(out / f"{camera_id}.mask.png", union)
        save_image(out / f"{camera_id}.instances.png", instances)
        annotation = {
            "version": "5.6.0",
            "flags": {"scene_objects_only": True},
            "shapes": shapes,
            "imagePath": f"{camera_id}.jpg",
            "imageData": None,
            "imageHeight": height,
            "imageWidth": width,
            "annotation_metadata": {
                "method": "assistant visually traced polygons; rendered with OpenCV",
                "accuracy": "approximate visible outlines; small appendages are simplified",
                "person_annotations_complete": False,
                "unsafe_as_hard_person_exclusion_mask": True,
                "objects": [
                    {"id": i, "name": o["name"], "label": o["label"]} for i, o in enumerate(objects, 1)
                ],
            },
        }
        (out / f"{camera_id}.json").write_text(
            json.dumps(annotation, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        preview = cv2.resize(annotated, (1296, 972))
        panel = np.full((972, 420, 3), 24, np.uint8)
        cv2.putText(panel, camera_id, (12, 32), cv2.FONT_HERSHEY_SIMPLEX, 0.9, (255, 255, 255), 2)
        for i, obj in enumerate(objects, 1):
            cv2.putText(
                panel,
                f"{i:02d} {obj['name']}",
                (12, 60 + 32 * i),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.48,
                (230, 230, 230),
                1,
            )
        review = np.hstack([preview, panel])
        save_image(out / f"{camera_id}.review.jpg", review)
        overview.append(cv2.resize(preview, (648, 486)))
        sources.append(
            {
                "camera_id": camera_id,
                "source_video": source.as_posix(),
                "frame_index": frame.index,
                "video_time_sec": frame.video_time_sec,
                "media_time_sec": frame.media_time_sec,
                "width": width,
                "height": height,
            }
        )
        counts[camera_id] = {"objects": len(objects), "polygon_components": shape_count}
    overview.append(np.full_like(overview[0], 24))
    sheet = np.vstack([np.hstack(overview[:3]), np.hstack(overview[3:])])
    save_image(out / "overview.jpg", sheet)
    (out / "sources.json").write_text(json.dumps(sources, indent=2), encoding="utf-8")
    (out / "summary.json").write_text(json.dumps(counts, indent=2), encoding="utf-8")
    print(json.dumps(counts, indent=2))


if __name__ == "__main__":
    main()
